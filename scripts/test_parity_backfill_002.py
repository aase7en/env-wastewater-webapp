class MigrationFileContract(unittest.TestCase):
    """Static shape of the ONE migration — phase-independent."""

    def test_file_exists_single(self):
        self.assertTrue(MIGRATION_PATH.exists())

    def test_every_seed_guarded(self):
        sql = MIGRATION_PATH.read_text(encoding="utf-8")
        for line in sql.splitlines():
            s = line.strip().lower()
            if s.startswith("insert into"):
                self.assertIn("where not exists", s, f"unguarded INSERT: {line[:80]}")

    def test_no_forbidden_statements(self):
        import re
        raw = MIGRATION_PATH.read_text(encoding="utf-8")
        # strip comment lines first — the header DOCUMENTS rollback SQL
        sql = "\n".join(ln for ln in raw.splitlines() if not ln.lstrip().startswith("--")).lower()
        for pat in (r"^\s*update\s", r"^\s*delete\s+from\s", r"alter type",
                    r"^\s*drop\s+(table|view|policy|type)\s",
                    r"create or replace view",
                    r"disable row level security"):
            self.assertIsNone(re.search(pat, sql, re.M), f"forbidden statement pattern: {pat}")

    def test_no_pii_patterns_in_artifact(self):
        import re
        sql = MIGRATION_PATH.read_text(encoding="utf-8")
        self.assertNotIn("พี่ชัย", sql, "personal-name note leaked into the migration")
        self.assertNotIn("ห้องควบคุมโรคติดต่อ", sql, "ink place value leaked into the migration")
        self.assertIsNone(re.search(r"\d{13}", sql), "13-digit pattern in migration")


