def token() -> str:
    """Secrets chain: process env → _env.load_secret (stub/Drive) → direct
    A_WIKI_DRIVE_PATH secrets file (worktrees carry no .env stub)."""
    global _token
    if _token is None:
        import os
        val = os.environ.get("SUPABASE_ACCESS_TOKEN", "")
        if not val:
            try:
                from _env import load_secret as _ls
                val = _ls("SUPABASE_ACCESS_TOKEN")
            except Exception:
                val = ""
        if not val:
            drive = os.environ.get("A_WIKI_DRIVE_PATH", "")
            if drive:
                cand = Path(drive) / "secrets" / "env-wastewater-webapp.env"
                if cand.exists():
                    for line in cand.read_text(encoding="utf-8").splitlines():
                        if line.startswith("SUPABASE_ACCESS_TOKEN="):
                            val = line.split("=", 1)[1].strip()
                            break
        _token = val
    return _token


_PACE = 2.5  # s between Management-API calls — the query endpoint throttles hard
             # after bulk applies; pacing is transport-only (assertions unchanged)


def q(sql: str):
    """Run one SELECT. Returns (ok, rows|error-string)."""
    import time
    time.sleep(_PACE)
    r = httpx.post(
        API_URL,
        headers={"Authorization": f"Bearer {token()}", "Content-Type": "application/json"},
        json={"query": sql},
        timeout=60,
    )
    if r.status_code >= 400:
        try:
            return False, r.json().get("message") or r.text
        except Exception:
            return False, r.text
    return True, r.json()


def scalar(sql: str):
    ok, rows = q(sql)
    if not ok or not rows:
        raise AssertionError(f"scalar query failed: {sql[:120]} → {rows}")
    return list(rows[0].values())[0]


def phase() -> str:
    ok, rows = q(
        "select count(*)::int n from information_schema.columns "
        "where table_schema='carbon' and table_name='reading' "
        "and column_name='activity_subtype'"
    )
    if not ok:
        return "PRE"
    return "POST" if rows[0]["n"] == 1 else "PRE"


